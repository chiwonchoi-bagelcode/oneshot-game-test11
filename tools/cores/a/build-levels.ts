// Writes src/cores/a/levels.ts from tools/cores/a/design.ts.   node tools/cores/a/build-levels.ts
import { writeFileSync } from 'node:fs';
import { build } from './lib.ts';
import { SPECS } from './design.ts';

const out: string[] = [];
let bad = 0;
for (const s of SPECS) {
  const b = build(s);
  console.log(b.report + '\n');
  if (b.metrics.solutions < 1 || b.metrics.solutions > (s.allow ?? 1) || b.metrics.fewer) bad++;
  const d = b.def;
  const lines = [
    '  {',
    `    id: ${JSON.stringify(d.id)},`,
    `    map: [\n${d.map.map((r) => '      ' + JSON.stringify(r) + ',').join('\n')}\n    ],`,
    `    goal: [\n${d.goal.map((r) => '      ' + JSON.stringify(r) + ',').join('\n')}\n    ],`,
    `    inks: ${JSON.stringify(d.inks)},`,
    `    solution: ${JSON.stringify(d.solution).replace(/"(\w)":/g, '$1: ').replace(/,(?=\w)/g, ', ').replace(/\{/g, '{ ').replace(/\}/g, ' }')},`,
  ];
  if (d.intro) lines.push(`    intro: ${JSON.stringify(d.intro)},`);
  if (d.guided) lines.push('    guided: true,');
  if (d.tag) lines.push(`    tag: ${JSON.stringify(d.tag)},`);
  if (d.coach) lines.push(`    coach: ${JSON.stringify(d.coach)},`);
  lines.push(`    diff: ${Math.round(Math.min(100, (1 - b.metrics.safe) * 60 + Math.log10(1 + b.metrics.branch) * 6))},`);
  lines.push('  },');
  out.push(lines.join('\n'));
}
const src = `// Core A: the 30 stages (tutorial included). Generated by tools/cores/a/build-levels.ts from
// tools/cores/a/design.ts — edit the design file and rebuild instead of editing this file.
import type { LevelDef } from '../../core/sim.ts';

export const LEVELS: LevelDef[] = [
${out.join('\n')}
];
`;
writeFileSync(new URL('../../../src/cores/a/levels.ts', import.meta.url), src);
console.log(`wrote ${SPECS.length} levels${bad ? `, ${bad} with problems` : ''}`);
