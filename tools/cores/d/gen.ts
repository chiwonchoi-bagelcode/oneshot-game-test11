/*
 * Core D stage generator: turns the hand-made stage specs (board, wells, intended plan) into
 * src/cores/d/levels.ts. The goal of each stage is picked automatically from the intended
 * plan's final board (see pickGoal) unless the spec gives one.
 *
 *   node tools/cores/d/gen.ts            write levels.ts
 *   node tools/cores/d/gen.ts --dry 5    only print stage 5
 */
import { writeFileSync } from 'node:fs';
import type { LevelDef } from '../../../src/core/sim.ts';
import { planToDrops, runPlan } from '../../../src/cores/d/rules.ts';
import { STAGES } from './stages.ts';
import { pickGoal, withInks, measureD, finalBoard } from './lib.ts';

const args = process.argv.slice(2);
const dry = args.includes('--dry');
const only = dry ? +args[args.indexOf('--dry') + 1] : 0;

const out: LevelDef[] = [];
let failed = false;
STAGES.forEach((sp, i) => {
  const num = i + 1;
  if (only && num !== only) return;
  const id = 'd' + String(num).padStart(2, '0');
  const base: LevelDef = withInks({ id, map: sp.map, goal: sp.map.map((r) => '.'.repeat(r.length)), inks: [], wells: sp.wells, solution: [] });
  let goal = sp.goal;
  let log: string[] = [];
  if (!goal) ({ goal, log } = pickGoal(base, sp.plan, sp.pick || {}));
  const def: LevelDef = { ...base, goal, solution: planToDrops(base, sp.plan) };
  if (sp.intro) def.intro = sp.intro;
  if (sp.guided) def.guided = true;
  if (sp.tag) def.tag = sp.tag;
  if (sp.coach) def.coach = sp.coach;
  const r = runPlan(def, sp.plan);
  if (r.result !== 'win') {
    failed = true;
    console.log(id, 'INTENDED PLAN DOES NOT WIN:', r.result, r.errors.join('; '));
  }
  const m = measureD(def);
  def.diff = Math.round(Math.min(100, (1 - m.random) * 40 + (1 - m.preview) * 30 + Math.min(4, m.drops) * 5 + Math.min(3, m.maxT) * 3));
  out.push(def);
  console.log(`${id} ${sp.intro ? '[' + sp.intro + '] ' : ''}wells ${m.wells} drops ${m.drops} maxT ${m.maxT} | sols ${m.solutions} sets ${m.wellSets} zeroOK ${m.allAtZero} | random ${(m.random * 100).toFixed(1)}% preview ${(m.preview * 100).toFixed(0)}% | diff ${def.diff} ${log.join(' ')}`);
  if (dry) {
    const F = finalBoard(base, sp.plan);
    console.log(goal.join('\n'));
    console.log('--- final board');
    console.log(F.ascii());
  }
});

if (!dry) {
  const lines = out.map((d) => '  ' + JSON.stringify(d).replace(/"(\w+)":/g, '$1: ').replace(/,(?=[a-z]+: )/g, ', ') + ',');
  const src = `// Core D: the 30 stages (tutorial included). Generated by tools/cores/d/gen.ts from tools/cores/d/stages.ts — edit the specs, not this file.
import type { LevelDef } from '../../core/sim.ts';

export const LEVELS: LevelDef[] = [
${lines.join('\n')}
];
`;
  writeFileSync(new URL('../../../src/cores/d/levels.ts', import.meta.url), src);
  console.log('wrote', out.length, 'stages', failed ? '(WITH FAILURES)' : '');
}
if (failed) process.exitCode = 1;
